def emoji_for(item: dict[str, Any]) -> str:
    name = str(item.get("name") or "").strip()
    if not name:
        return FALLBACK_EMOJI
    if name in NAME_EMOJI:
        return NAME_EMOJI[name]
    for needle, emoji in KEYWORD_EMOJI:
        if needle in name:
            return emoji
    return GROUP_EMOJI.get(str(item.get("group_code") or ""), FALLBACK_EMOJI)


def _asset_code(emoji: str) -> str:
    codepoints = [ord(char) for char in emoji if char not in {"\ufe0f", "\u200d"}]
    return "-".join(f"{point:x}" for point in codepoints) or "1f6cd"


def _fetch_art(code: str) -> bytes:
    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    cached = CACHE_DIR / f"{code}.png"
    if cached.exists():
        return cached.read_bytes()
    url = f"{TWEMOJI_BASE}/{code}.png"
    response = requests.get(url, timeout=60)
    response.raise_for_status()
    cached.write_bytes(response.content)
    return response.content


def render_thumbnail(item: dict[str, Any]) -> bytes:
    """Return a crisp 256x256 white-background picture for one catalog item."""
    code = _asset_code(emoji_for(item))
    try:
        raw = _fetch_art(code)
    except Exception:
        raw = _fetch_art(_asset_code(FALLBACK_EMOJI))

    with Image.open(io.BytesIO(raw)) as source:
        art = source.convert("RGBA")
        ratio = min(ART_SIZE / art.width, ART_SIZE / art.height)
        art = art.resize(
            (max(1, round(art.width * ratio)), max(1, round(art.height * ratio))),
            Image.Resampling.LANCZOS,
        )

    canvas = Image.new("RGB", (SIZE, SIZE), "white")
    ImageDraw.Draw(canvas).rounded_rectangle(
        (2, 2, SIZE - 3, SIZE - 3), radius=24, outline="#E7EBF1", width=2
    )
    canvas.paste(art, ((SIZE - art.width) // 2, (SIZE - art.height) // 2), art)

    buffer = io.BytesIO()
    canvas.save(buffer, format="PNG", optimize=True)
    return buffer.getvalue()
